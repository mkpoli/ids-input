const kage = new Kage()
kage.kShotai = kage.kGothic
kage.kFont.kWidth = 7
for (const [name, data] of Object.entries(BUHIN)) {
  kage.kBuhin.push(name, data)
  if (name.includes('@')) kage.kBuhin.push(name.split('@')[0], data)
}

const paths = {}
for (const [key, source] of Object.entries(GLYPHWIKI_SOURCES)) {
  const polygons = new Polygons()
  kage.makeGlyph2(polygons, BUHIN[source])
  paths[key] = polygons.array.map(polygon => {
    const points = polygon.array.map(({ x, y }) => [x, y])
    if (area(points) < 0) points.reverse()
    return 'M' + points.map(point => point.join(' ')).join('L') + 'Z'
  }).join('')
}

// Width controls are checked in the built workshop, including the responsive layouts they resize.
export async function checkPanelWidths(open, assert) {
  const page = await open()
  try {
    const input = page.locator('.input-gap [role="separator"]')
    const output = page.locator('.output-gap [role="separator"]')
    const width = selector => page.locator(selector).evaluate(el => el.getBoundingClientRect().width)
    const value = separator => separator.getAttribute('aria-valuenow').then(Number)
    const resize = async (width, height = 900) => {
      await page.setViewportSize({ width, height })
      // Let the ResizeObserver measurement and the resulting grid update reach the screen.
      await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    }
    const fits = async () => {
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'columns fit the viewport')
      assert(await width('.middle') >= 279, 'the middle column stays usable')
    }
    async function drag(separator, dx) {
      const grip = await separator.locator('.grip').boundingBox()
      const x = grip.x + grip.width / 2, y = grip.y + grip.height / 2
      assert(y > 0 && y < 900, 'the width grip is visible')
      await page.mouse.move(x, y)
      await page.mouse.down()
      await page.mouse.move(x + dx, y, { steps: 5 })
      await page.mouse.up()
    }
    await input.waitFor()
    assert(await output.isVisible(), 'both desktop width dividers are visible')
    assert(await input.getAttribute('aria-orientation') === 'vertical', 'width divider has vertical orientation')
    assert(await input.getAttribute('aria-controls') === 'input-panel' && await output.getAttribute('aria-controls') === 'output-panel', 'each divider names the panel it resizes')
    const initialOutput = await width('.pane.output')
    await drag(input, 90)
    assert(Math.abs(await width('.pane.input') - 470) < 2, 'dragging the first gap widens the input')
    assert(Math.abs(await width('.pane.output') - initialOutput) < 2, 'input drag preserves output width')
    await drag(output, -60)
    assert(Math.abs(await width('.pane.output') - initialOutput - 60) < 2, 'dragging the second gap left widens the output')
    assert(Math.abs(await width('.pane.input') - 470) < 2, 'output drag preserves input width')
    const sequence = await page.locator('.ids-field input').inputValue()
    await input.focus()
    const beforeKey = await value(input)
    await page.keyboard.press('ArrowLeft')
    assert(await value(input) === beforeKey - 10, 'Left moves the input divider left')
    await page.keyboard.press('Shift+ArrowRight')
    assert(await value(input) === beforeKey + 40, 'Shift takes a larger step')
    await output.focus()
    await page.keyboard.press('ArrowRight')
    assert(Math.abs(await width('.pane.output') - initialOutput - 50) < 2, 'Right moves the output divider right')
    await page.keyboard.press('Home')
    assert(await value(output) === Number(await output.getAttribute('aria-valuemin')), 'Home reaches the minimum panel width')
    await page.locator('.export [role="radio"]', { hasText: 'PNG' }).click()
    assert(await page.locator('.pane.output').evaluate(el => el.scrollWidth <= el.clientWidth), 'PNG controls fit the minimum output width')
    await input.focus(); await page.keyboard.press('Home')
    await output.focus()
    await page.keyboard.press('End')
    assert(await value(output) === Number(await output.getAttribute('aria-valuemax')), 'End reaches the maximum panel width')
    assert(await page.locator('.ids-field input').inputValue() === sequence, 'divider keys do not edit the tree')
    await fits()
    await input.locator('.grip').dblclick()
    await output.locator('.grip').dblclick()
    assert(await value(input) === 380 && await value(output) === 400, 'double-click restores default widths')
    await resize(1024)
    assert(await value(input) === 360, 'resetting both columns preserves the adaptive tablet default')
    await resize(1440)
    await input.focus(); await page.keyboard.press('Shift+ArrowRight')
    await output.focus(); await page.keyboard.press('ArrowLeft')
    await page.reload(); await input.waitFor()
    assert(await value(input) === 430 && await value(output) === 410, 'both widths survive reload')

    await resize(1900)
    await input.focus(); await page.keyboard.press('End')
    const wideInput = await value(input)
    await resize(1280)
    await fits()
    assert(await value(input) < wideInput, 'saved widths shrink to fit a narrower desktop')
    await resize(1900)
    assert(await value(input) === wideInput, 'growing the window restores the requested width')
    await resize(1024)
    assert(await input.isVisible() && !await output.isVisible(), 'tablet only shows the gap between adjacent columns')
    await fits()
    await input.locator('.grip').dblclick()
    assert(await value(input) === 360, 'tablet resets to its default input width')
    await drag(input, 50)
    assert(await value(input) === 410, 'the tablet divider resizes the input')
    await resize(375, 812)
    assert(!await input.isVisible() && !await output.isVisible(), 'stacked mobile panels hide width controls')
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile remains within the viewport')
    await resize(1440)
    assert(await value(input) === 410 && await value(output) === 410, 'returning to desktop restores both widths')
    assert(!page.errors.length, `column page errors: ${page.errors.join('; ')}`)
  } finally { await page.context().close() }
}

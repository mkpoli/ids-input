// Run against a devrun server: IDS_URL=http://localhost:5173 bun demo/check-hangul-parts.js
import { chromium } from 'playwright-core'
import { strict as assert } from 'node:assert'

const cluster = (...points) => String.fromCodePoint(...points)
const oldFinal = cluster(0x11eb), oldSyllable = cluster(0x1100, 0x1161, 0x11eb)
const view = async (page, name) => page.locator('.hangul-views').getByRole('button', { name, exact: true }).click()
const key = (page, char) => page.locator(`.hangul-compose [data-jamo="${char}"]`)
const result = page => page.locator('.compose-result')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
try {
  const page = await browser.newPage()
  await page.goto(process.env.IDS_URL ?? 'http://localhost:5173')
  await page.getByRole('tab', { name: 'Parts', exact: true }).click()
  await page.getByRole('tab', { name: 'Hangul', exact: true }).click()
  await page.locator('.parts-grid .part').first().waitFor()
  assert.equal(await page.locator('.hangul-views button[aria-pressed="true"]').innerText(), 'Jamo')
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '◇')
  const filter = page.locator('.parts-filter')
  for (const part of ['◇', 'ᄓ', '㉠', '〮']) {
    await filter.fill(part)
    assert.equal(await page.locator('.parts-grid .part').count(), 1, part)
    assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), part)
  }
  await filter.fill('')

  await view(page, 'Compose')
  assert.equal(await page.locator('.parts-filter').count(), 0)
  const emptyResult = await result(page).getAttribute('data-character')
  assert.ok(emptyResult === null || emptyResult === '', 'no syllable yet')
  assert.equal(await result(page).isDisabled(), true)
  await key(page, 'ㄱ').click()
  const initialOnly = await result(page).getAttribute('data-character')
  assert.ok(initialOnly === null || initialOnly === '', 'no vowel yet')
  await key(page, 'ㅏ').click()
  assert.equal(await result(page).getAttribute('data-character'), '가')
  assert.equal(await result(page).isDisabled(), false)
  await key(page, 'ㄴ').click()
  assert.equal(await result(page).getAttribute('data-character'), '간')
  await page.locator('.compose-backspace').click()
  assert.equal(await result(page).getAttribute('data-character'), '가')
  await key(page, 'ㄳ').click()
  assert.equal(await result(page).getAttribute('data-character'), '갃')
  await key(page, oldFinal).click()
  assert.equal(await result(page).getAttribute('data-character'), oldSyllable)
  assert.match(await page.locator('.hangul-compose .parts-note').innerText(), /Old Hangul is kept/)
  await page.locator('.compose-clear').click()
  const cleared = await result(page).getAttribute('data-character')
  assert.ok(cleared === null || cleared === '', 'cleared')
  await key(page, 'ㅏ').click()
  assert.equal(await result(page).getAttribute('data-character'), '아')
  await page.locator('.compose-clear').click()

  await view(page, 'Syllable')
  await page.locator('.parts-grid .part').first().waitFor()
  assert.equal(await page.locator('.parts-grid .part').count(), 120)
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '가')
  assert.match(await page.locator('.script-pages').innerText(), /11,?172/)
  await filter.fill('가')
  assert.equal(await page.locator('.parts-grid .part').count(), 1)
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '가')
  await filter.fill('ㄱㅏ')
  assert.equal(await page.locator('.parts-grid .part').count(), 1)
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '가')
  await filter.fill('U+D7A3')
  assert.equal(await page.locator('.parts-grid .part').count(), 1)
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '힣')
  await filter.fill('gan')
  assert.equal(await page.locator('.parts-grid .part').count(), 3)
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '간')
  await filter.fill('GAN')
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '간')
  await filter.fill('gak')
  assert.equal(await page.locator('.parts-grid .part').count(), 5)
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '각')
  await filter.fill('tchak')
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '짝')
  await filter.fill('')

  // The fragment form, kept as cover for links written before the sequence moved to the path.
  const draft = await browser.newPage()
  await draft.goto(new URL('/#' + encodeURIComponent('⿰⬚木'), process.env.IDS_URL ?? 'http://localhost:5173').href)
  await draft.getByRole('tab', { name: 'Parts', exact: true }).click()
  await draft.getByRole('tab', { name: 'Hangul', exact: true }).click()
  await view(draft, 'Compose')
  await key(draft, 'ㄱ').click()
  await key(draft, 'ㅏ').click()
  await result(draft).click()
  const field = draft.locator('.ids-field input').first()
  assert.equal(await field.inputValue(), '⿰가木')
  assert.notEqual(await field.getAttribute('aria-invalid'), 'true')
  await draft.close()

  const adjacent = await browser.newPage()
  await adjacent.goto(new URL('/#' + encodeURIComponent('⿰⬚⬚'), process.env.IDS_URL ?? 'http://localhost:5173').href)
  await adjacent.getByRole('tab', { name: 'Parts', exact: true }).click()
  await adjacent.getByRole('tab', { name: 'Hangul', exact: true }).click()
  await adjacent.locator('.ids-tree [data-path="0"]').click()
  await adjacent.locator('.parts-filter').fill(String.fromCodePoint(0x1100))
  await adjacent.locator('.parts-grid .part').first().click()
  await adjacent.waitForTimeout(700)
  await adjacent.locator('.ids-tree [data-path="1"]').click()
  await adjacent.locator('.parts-filter').fill(String.fromCodePoint(0x1161))
  await adjacent.locator('.parts-grid .part').first().click()
  await adjacent.waitForTimeout(700)
  assert.equal(await adjacent.locator('.ids-field input').first().inputValue(), `⿰${String.fromCodePoint(0x1100)}⬚`)
  assert.match(await adjacent.locator('.status').first().innerText(), /read back as different parts/)
  await adjacent.close()

  const fixture = await browser.newPage()
  await fixture.goto(new URL('/fixtures/hangul-parts.html', process.env.IDS_URL ?? 'http://localhost:5173').href)
  await fixture.getByRole('tab', { name: 'Hangul', exact: true }).click()
  await view(fixture, 'Compose')
  await key(fixture, 'ㄱ').click()
  await key(fixture, 'ㅏ').click()
  await result(fixture).click()
  assert.equal(await fixture.locator('#picked').textContent(), '가')
  await key(fixture, 'ㄱ').click()
  await key(fixture, 'ㅏ').click()
  await key(fixture, oldFinal).click()
  await result(fixture).click()
  assert.equal(await fixture.locator('#picked').textContent(), oldSyllable)
  await view(fixture, 'Jamo')
  for (const query of ['42', 'hangul-alias']) {
    await fixture.locator('.parts-filter').fill(query)
    assert.equal(await fixture.locator('.parts-grid .part').count(), 1)
    assert.equal(await fixture.locator('.parts-grid .part').first().getAttribute('data-character'), 'ㅏ')
  }
  await fixture.close()
  console.log('PASS Hangul Jamo, Compose and Syllable views, jamo keyboard, old Hangul and search')
} finally { await browser.close() }

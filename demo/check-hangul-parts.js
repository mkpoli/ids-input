// Run against a devrun server: IDS_URL=http://localhost:5173 bun demo/check-hangul-parts.js
import { chromium } from 'playwright-core'
import { strict as assert } from 'node:assert'

const cluster = (...points) => String.fromCodePoint(...points)
const k = cluster(0x11a8), oldFinal = cluster(0x11eb), oldSyllable = cluster(0x1100, 0x1161, 0x11eb)
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
try {
  const page = await browser.newPage()
  await page.goto(process.env.IDS_URL ?? 'http://localhost:5173')
  await page.getByRole('tab', { name: 'Parts', exact: true }).click()
  await page.getByRole('tab', { name: 'Hangul', exact: true }).click()
  const select = page.getByRole('combobox', { name: 'Show', exact: true })
  await page.locator('.parts-grid .part').first().waitFor()
  assert.equal(await select.inputValue(), 'parts')
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '◇')
  const filter = page.locator('.parts-filter')
  for (const part of ['◇', 'ᄓ', '㉠', '〮']) {
    await filter.fill(part)
    assert.equal(await page.locator('.parts-grid .part').count(), 1, part)
    assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), part)
  }
  await select.selectOption('compose')
  assert.equal(await select.inputValue(), 'compose')
  const result = page.locator('.compose-result')
  await result.waitFor()
  assert.equal(await result.getAttribute('data-character'), '가')
  const final = page.getByRole('combobox', { name: 'Final', exact: true })
  await final.selectOption(k)
  assert.equal(await result.getAttribute('data-character'), '각')
  await final.selectOption(oldFinal)
  assert.equal(await result.getAttribute('data-character'), oldSyllable)
  assert.match(await page.locator('.hangul-compose .parts-note').innerText(), /Old Hangul/)
  await filter.fill('가')
  assert.equal(await page.locator('.parts-grid .part').count(), 1)
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '가')
  await filter.fill('ㄱㅏ')
  assert.equal(await page.locator('.parts-grid .part').count(), 1)
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '가')
  await filter.fill('U+D7A3')
  assert.equal(await page.locator('.parts-grid .part').count(), 1)
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '힣')
  await filter.fill('')
  await result.waitFor()
  const draft = await browser.newPage()
  await draft.goto(new URL('/#' + encodeURIComponent('⿰⬚木'), process.env.IDS_URL ?? 'http://localhost:5173').href)
  await draft.getByRole('tab', { name: 'Parts', exact: true }).click()
  await draft.getByRole('tab', { name: 'Hangul', exact: true }).click()
  await draft.getByRole('combobox', { name: 'Show', exact: true }).selectOption('compose')
  await draft.getByRole('combobox', { name: 'Final', exact: true }).selectOption(oldFinal)
  await draft.locator('.compose-result').click()
  const field = draft.locator('.ids-field input').first()
  assert.equal(await field.inputValue(), `⿰${oldSyllable}木`)
  assert.notEqual(await field.getAttribute('aria-invalid'), 'true')
  await draft.close()
  const fixture = await browser.newPage()
  await fixture.goto(new URL('/fixtures/hangul-parts.html', process.env.IDS_URL ?? 'http://localhost:5173').href)
  await fixture.getByRole('tab', { name: 'Hangul', exact: true }).click()
  const fixtureSelect = fixture.getByRole('combobox', { name: 'Show', exact: true })
  await fixtureSelect.selectOption('compose')
  await fixture.locator('.compose-result').click()
  assert.equal(await fixture.locator('#picked').textContent(), '가')
  await fixture.getByRole('combobox', { name: 'Final', exact: true }).selectOption(oldFinal)
  await fixture.locator('.compose-result').click()
  assert.equal(await fixture.locator('#picked').textContent(), oldSyllable)
  await fixtureSelect.selectOption('parts')
  for (const query of ['42', 'hangul-alias']) {
    await fixture.locator('.parts-filter').fill(query)
    assert.equal(await fixture.locator('.parts-grid .part').count(), 1)
    assert.equal(await fixture.locator('.parts-grid .part').first().getAttribute('data-character'), 'ㅏ')
  }
  await fixture.close()
  console.log('PASS Hangul parts by default, historical marks, jamo composition, old Hangul and search')
} finally { await browser.close() }

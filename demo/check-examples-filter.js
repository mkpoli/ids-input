// The starter popover and the examples menu: + opens a blank tab; the chevron opens a dialog whose
// Templates tab is the full template catalogue and whose Examples tab is the examples list, while the
// toolbar keeps its own Examples menu. Run against a devrun server:
//   IDS_URL=http://localhost:5173 CHROMIUM_PATH=… bun demo/check-examples-filter.js
import { chromium } from 'playwright-core'
import { strict as assert } from 'node:assert'
import { pyramidSequence } from '../src/core/pyramid.js'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
const url = process.env.IDS_URL ?? 'http://localhost:5173'
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await page.goto(url)
  await page.waitForTimeout(3000)
  await page.locator('.ids-field input').waitFor({ timeout: 20000 })
  const tabs = () => page.locator('.tabbar .tabs [role="tab"]').count()
  const opened = await tabs()
  const trigger = page.getByTitle('Templates, examples and closed tabs', { exact: true })
  const dialog = page.getByRole('dialog', { name: 'Templates, examples and closed tabs' })

  await page.getByTitle('New tab', { exact: true }).click()
  await page.waitForTimeout(300)
  assert.equal(await tabs(), opened + 1, 'the + opens a blank tab')
  assert.equal(await page.locator('.ids-field input').inputValue(), '', 'the new tab is empty')

  await trigger.click()
  await dialog.waitFor()
  const templatesTab = dialog.getByRole('tab', { name: 'Templates', exact: true })
  const examplesTab = dialog.getByRole('tab', { name: 'Examples', exact: true })
  assert.equal(await templatesTab.getAttribute('aria-selected'), 'true', 'the dialog opens on Templates')
  const structures = dialog.locator('.ids-template-grid button[data-template]')
  assert.ok(await structures.count() > 10, 'the full structure catalogue is here')
  assert.ok(await dialog.locator('[data-pyramid]').count() >= 10, 'the pyramid sizes are here')
  assert.equal(await dialog.locator('.ids-repeat-grid button[data-repeat]').count(), 4, 'the repeat templates are here')

  const sequence = await structures.first().getAttribute('data-sequence')
  await structures.first().click()
  await page.waitForTimeout(400)
  assert.equal(await tabs(), opened + 2, 'a template opens a new tab')
  assert.equal(await page.locator('.ids-field input').inputValue(), sequence, 'the tab holds the template')
  assert.equal(await dialog.count(), 0, 'the dialog closes')

  await trigger.click()
  await dialog.waitFor()
  await dialog.locator('[data-pyramid="3"]').click()
  await page.waitForTimeout(400)
  assert.equal(await page.locator('.ids-field input').inputValue(), pyramidSequence('口', 3), 'a pyramid opens a new tab')
  assert.equal(await tabs(), opened + 3, 'the pyramid tab is new')

  await page.getByTitle('Examples', { exact: true }).click()
  await page.locator('.menu').waitFor()
  assert.ok(await page.locator('.menu .card').count() > 100, 'the toolbar Examples menu still lists the examples')
  // A 二簡字 card names the standard it replaces in both scripts, each with its code point.
  const erjianCard = page.locator('.menu .card').filter({ hasText: '弹 彈' }).first()
  assert.ok(await erjianCard.count(), 'the Erjian card names both scripts')
  assert.doesNotMatch(await erjianCard.locator('.card-note').innerText(), /U\+/, 'the unencoded form carries no code point')
  const encodedErjian = page.locator('.menu .card').filter({ hasText: 'U+327F1' }).first()
  assert.ok(await encodedErjian.count(), 'the encoded Erjian form keeps its code point')
  assert.match(await encodedErjian.locator('.card-note').innerText(), /U\+327F1 · 警/, 'the encoded form names its code point and standard')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)

  await trigger.click()
  await dialog.waitFor()
  await examplesTab.click()
  await page.waitForTimeout(300)
  const input = dialog.locator('.filter-input')
  assert.equal(await input.count(), 1, 'the examples tab has a filter field')
  const total = await dialog.locator('.card').count()
  assert.ok(total > 100, 'the cards start expanded')
  // The categories wrap instead of scrolling sideways, so every chip is readable at once.
  const jump = dialog.locator('.jump')
  const chips = jump.locator('.ui-chip')
  assert.ok(await chips.count() > 10, 'the categories fill the chip row')
  const lines = new Set(await chips.evaluateAll(nodes => nodes.map(node => Math.round(node.getBoundingClientRect().top))))
  assert.ok(lines.size > 1, 'the chips take more than one line')
  assert.ok(await jump.evaluate(node => node.scrollWidth <= node.clientWidth + 1), 'the wrapped row does not scroll sideways')
  assert.ok(await jump.isVisible(), 'the dialog keeps its category chips')
  const jumpBox = await jump.boundingBox(), lastBox = await chips.last().boundingBox()
  assert.ok(lastBox.x + lastBox.width <= jumpBox.x + jumpBox.width + 1, 'the last chip stays inside the row')
  // Each collapsible heading says how many items its section holds.
  const names = await dialog.locator('button.heading .heading-name').allTextContents()
  const numbers = await dialog.locator('button.heading .count').allTextContents()
  assert.equal(numbers.length, names.length, 'every section heading has a count')
  for (const [i, number] of numbers.entries()) assert.match(number, /^[1-9]\d*$/, `the ${names[i]} heading counts its items`)
  const koreanHeading = dialog.locator('button.heading', { hasText: 'Korean gukja' }).first()
  const koreanCount = await koreanHeading.locator('.count').textContent()
  assert.ok(Number(koreanCount) > 50, 'the Korean gukja count is the size of its section')
  assert.equal(await koreanHeading.getAttribute('aria-label'), `Korean gukja, ${koreanCount}`, 'the count is part of the heading name')
  await input.fill('乙')
  await page.waitForTimeout(300)
  const filtered = await dialog.locator('.card').count()
  assert.ok(filtered > 0 && filtered < total, 'the query narrows the cards')
  assert.match(await dialog.locator('.card-label').first().textContent(), /乙/, 'a match shows the 乙 in its sequence')
  const counted = (await dialog.locator('button.heading .count').allTextContents()).reduce((sum, number) => sum + Number(number), 0)
  assert.equal(counted, filtered, 'the counts add up to the cards the query keeps')
  await input.fill('')
  await dialog.getByRole('button', { name: 'Code point', exact: true }).click()
  await page.waitForTimeout(200)
  assert.equal(await dialog.locator('.card', { hasText: '(unencoded)' }).count(), 0, 'the code-point filter hides unencoded cards')
  assert.equal(await dialog.locator('.card', { hasText: '弹 彈' }).count(), 0, 'the code-point filter hides the unencoded Erjian form')
  assert.equal(await dialog.locator('.card', { hasText: 'U+327F1' }).count(), 1, 'the code-point filter shows the encoded Erjian form')
  await dialog.getByRole('button', { name: 'No code point', exact: true }).click()
  await page.waitForTimeout(200)
  assert.ok(await dialog.locator('.card').count() > 0, 'the unencoded filter shows the forms without a code point')
  assert.equal(await dialog.locator('.card', { hasText: '弹 彈' }).count(), 1, 'the unencoded filter shows the Erjian form')
  assert.equal(await dialog.locator('.card', { hasText: 'U+327F1' }).count(), 0, 'the unencoded filter hides the encoded Erjian form')
  assert.equal(await dialog.locator('.card', { hasText: '森' }).count(), 0, 'the encoded 森 is hidden')
  await dialog.getByRole('button', { name: 'All', exact: true }).click()
  await page.waitForTimeout(200)
  const heading = dialog.locator('button.heading', { hasText: 'Korean gukja' })
  await heading.scrollIntoViewIfNeeded()
  assert.equal(await dialog.locator('.card', { hasText: '㐎' }).count(), 1, 'the Korean section holds its cards')
  await heading.click()
  await page.waitForTimeout(300)
  assert.equal(await heading.getAttribute('aria-expanded'), 'false', 'a heading folds its section')
  assert.equal(await dialog.locator('.card', { hasText: '㐎' }).count(), 0, 'the folded section hides its cards')
  await heading.click()
  await page.waitForTimeout(300)
  assert.equal(await dialog.locator('.card', { hasText: '㐎' }).count(), 1, 'the section comes back')
  await dialog.locator('.view', { hasText: 'List' }).click()
  await page.waitForTimeout(300)
  const rows = await dialog.locator('.item').count()
  assert.ok(rows > 100, 'the list view holds the rows')
  await dialog.locator('.filter-input').fill('돌')
  await page.waitForTimeout(300)
  const shown = await dialog.locator('.item').count()
  assert.ok(shown > 0 && shown < rows, 'the list view filters too')
  assert.ok((await dialog.locator('.note').allTextContents()).some(note => note.includes('돌')), 'a reading matches the query')

  // An example opens its tab and leaves the focus in that tab's sequence field.
  await dialog.getByRole('button', { name: 'Cards', exact: true }).click()
  await dialog.locator('.filter-input').fill('')
  await page.waitForTimeout(300)
  const card = dialog.locator('.card').first()
  const cardText = (await card.locator('.card-label').textContent()).trim()
  await card.click()
  await page.waitForTimeout(400)
  assert.equal(await dialog.count(), 0, 'the dialog closes after an example')
  assert.equal(await page.locator('.ids-field input').inputValue(), cardText, 'the example opens its tab')
  assert.equal(await page.evaluate(() => document.activeElement?.closest('.ids-field') !== null), true, 'the focus moves into the example tab')

  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)

  // Keyboard: the chevron opens on Templates, the arrow keys and Home switch tabs, Escape gives the focus back.
  await page.getByTitle('New tab', { exact: true }).focus()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Enter')
  await dialog.waitFor()
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('role')), 'tab', 'Enter opens the dialog on a starter tab')
  await page.keyboard.press('Home')
  assert.equal(await templatesTab.getAttribute('aria-selected'), 'true', 'Home selects Templates')
  await page.keyboard.press('ArrowRight')
  assert.equal(await examplesTab.getAttribute('aria-selected'), 'true', 'Right moves to Examples')
  await page.keyboard.press('ArrowLeft')
  assert.equal(await templatesTab.getAttribute('aria-selected'), 'true', 'Left returns to Templates')
  await page.keyboard.press('Escape')
  assert.equal(await dialog.count(), 0, 'Escape closes the dialog')
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Templates, examples and closed tabs', 'Escape returns the focus to the chevron')

  // Picking a template leaves the focus in the new tab's sequence field.
  await trigger.click()
  await dialog.waitFor()
  await dialog.locator('[data-template]').first().click()
  await page.waitForTimeout(400)
  assert.equal(await page.evaluate(() => document.activeElement?.closest('.ids-field') !== null), true, 'the focus moves into the new tab')

  // The panel stays inside a phone-sized window, bottom included.
  await page.setViewportSize({ width: 375, height: 640 })
  await page.waitForTimeout(300)
  await trigger.click()
  await dialog.waitFor()
  await page.waitForTimeout(400)
  const box = await dialog.boundingBox()
  assert.ok(box && box.x >= 0 && box.x + box.width <= 375 && box.y >= 0 && box.y + box.height <= 640, `the panel fits a phone: ${JSON.stringify(box)}`)
  await page.keyboard.press('Escape')

  // The phone sheet keeps one Examples entry, and it opens the starter's Examples tab.
  await page.getByRole('button', { name: 'Menu', exact: true }).click()
  const sheet = page.locator('dialog[open]')
  await sheet.waitFor()
  await sheet.getByRole('button', { name: 'Open the examples', exact: true }).click()
  await dialog.waitFor()
  assert.equal(await examplesTab.getAttribute('aria-selected'), 'true', 'the phone menu opens the Examples tab')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(200)
  await page.setViewportSize({ width: 1440, height: 900 })

  // The phone's Examples tab is the same list in a narrow panel, so it keeps the chips, the fold
  // and the counts: every section folded, a count on each heading, and a chip that opens one.
  const narrow = await browser.newPage({ viewport: { width: 390, height: 844 } })
  await narrow.goto(url)
  await narrow.locator('.ids-field input').first().waitFor({ timeout: 60000 })
  await narrow.getByRole('button', { name: 'Menu', exact: true }).click()
  await narrow.getByRole('button', { name: 'Open the examples', exact: true }).click()
  const phoneDialog = narrow.getByRole('dialog', { name: 'Templates, examples and closed tabs' })
  await phoneDialog.waitFor()
  const phoneExamples = phoneDialog.locator('.list').last()
  const phoneHeads = phoneExamples.locator('button.heading')
  assert.ok(await phoneExamples.locator('.ui-chip').count() > 10, 'the phone still has its category chips')
  assert.equal(await phoneHeads.locator('.count').count(), await phoneHeads.count(), 'every heading on the phone has a count')
  assert.ok(await phoneExamples.locator('.card').count() > 0, 'the phone shows the examples')
  const phoneChip = phoneExamples.locator('.ui-chip', { hasText: 'Korean gukja' })
  await phoneChip.click()
  await narrow.waitForTimeout(400)
  assert.equal(await phoneChip.getAttribute('aria-current'), 'true', 'a phone chip marks its section')
  await narrow.close()
  console.log('PASS the starter dialog opens templates and examples in tabs, and the toolbar keeps its examples menu')
} finally { await browser.close() }

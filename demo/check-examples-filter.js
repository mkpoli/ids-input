// The tab strip's starter menu: + opens a blank tab, the templates open an operator tab, and the
// examples filter and fold in both views. Run against a devrun server:
//   IDS_URL=http://localhost:5173 CHROMIUM_PATH=… bun demo/check-examples-filter.js
import { chromium } from 'playwright-core'
import { strict as assert } from 'node:assert'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
const url = process.env.IDS_URL ?? 'http://localhost:5173'
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await page.goto(url)
  const tabs = () => page.locator('.tabbar [role="tab"]').count()
  const opened = await tabs()
  await page.getByTitle('New tab', { exact: true }).click()
  await page.waitForTimeout(300)
  assert.equal(await tabs(), opened + 1, 'the + opens a blank tab')
  assert.equal(await page.locator('.ids-field input').inputValue(), '', 'the new tab is empty')
  await page.getByTitle('Templates and examples', { exact: true }).click()
  const menu = page.locator('.menu')
  const templates = menu.getByRole('group', { name: 'Templates' })
  assert.equal(await templates.getByRole('menuitem').count(), 18, 'the templates list every operator')
  await templates.getByRole('menuitem', { name: 'Mirrored', exact: true }).click()
  await page.waitForTimeout(300)
  assert.equal(await page.locator('.ids-field input').inputValue(), '⿾⬚', 'a template opens its operator with empty slots')
  assert.equal(await tabs(), opened + 2, 'a template opens a new tab')
  await page.getByTitle('Templates and examples', { exact: true }).click()
  const input = menu.locator('.filter-input')
  assert.equal(await input.count(), 1, 'the examples menu has a filter field')
  const total = await menu.locator('.card').count()
  assert.ok(total > 100, 'the cards start expanded')
  const mode = async name => { await menu.getByRole('menuitemradio', { name, exact: true }).click(); await page.waitForTimeout(200) }
  await input.fill('乙')
  await page.waitForTimeout(300)
  const filtered = await menu.locator('.card').count()
  assert.ok(filtered > 0 && filtered < total, 'the query narrows the cards')
  assert.match(await menu.locator('.card-label').first().textContent(), /乙/, 'a match shows the 乙 in its sequence')
  await input.fill('')
  await mode('Code point')
  assert.equal(await menu.locator('.card', { hasText: '(unencoded)' }).count(), 0, 'the code-point filter hides unencoded cards')
  await mode('No code point')
  assert.ok(await menu.locator('.card').count() > 0, 'the unencoded filter shows the forms without a code point')
  assert.equal(await menu.locator('.card', { hasText: '森' }).count(), 0, 'the encoded 森 is hidden')
  const notes = await menu.locator('.card-note').allTextContents()
  assert.ok(notes.some(note => note.includes('(unencoded)')), 'a form without a code point says so')
  assert.ok(notes.some(note => note.includes('Abbreviation')), 'a Geba abbreviation counts as unencoded too')
  await mode('All')
  const heading = menu.locator('button.heading', { hasText: 'Korean gukja' })
  await heading.scrollIntoViewIfNeeded()
  const korean = await menu.locator('.card', { hasText: '㐎' }).count()
  assert.equal(korean, 1, 'the Korean section holds its cards')
  await heading.click()
  await page.waitForTimeout(300)
  assert.equal(await heading.getAttribute('aria-expanded'), 'false', 'a heading folds its section')
  assert.equal(await menu.locator('.card', { hasText: '㐎' }).count(), 0, 'the folded section hides its cards')
  await heading.click()
  await page.waitForTimeout(300)
  assert.equal(await menu.locator('.card', { hasText: '㐎' }).count(), 1, 'the section comes back')
  await menu.getByText('List', { exact: true }).click()
  await page.waitForTimeout(300)
  const rows = await menu.locator('.item').count()
  assert.ok(rows > 100, 'the list view holds the rows')
  await menu.locator('.filter-input').fill('돌')
  await page.waitForTimeout(300)
  const shown = await menu.locator('.item').count()
  assert.ok(shown > 0 && shown < rows, 'the list view filters too')
  assert.ok((await menu.locator('.note').allTextContents()).some(note => note.includes('돌')), 'a reading matches the query')
  console.log('PASS the tab strip starts a blank or template tab, and the examples filter and fold in both views')
} finally { await browser.close() }

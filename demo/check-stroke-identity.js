const assertNoStrokeSymbols = async palette => {
  assert.equal(await palette.locator('.part[data-component-type="stroke"]').count(), 0)
  assert.ok((await values(palette.locator('.part'))).every(part => !unicodeStrokes.includes(part)))
  assert.equal(await palette.locator('section.stroke-results').count(), 0)
}
const assertStrokeSection = async (palette, ordinaryCount, strokeCount) => {
  const section = palette.locator('section.stroke-results')
  assert.equal(await section.count(), 1, 'stroke results have one dedicated section')
  const region = palette.getByRole('region', { name: 'Stroke symbols', exact: true })
  assert.equal(await region.count(), 1, 'the stroke section has an accessible name')
  assert.equal(await region.evaluate(node => node.matches('section.stroke-results')), true)
  await section.getByRole('heading', { name: 'Stroke symbols', exact: true }).waitFor({ state: 'visible' })
  const cells = await palette.locator('.part').evaluateAll(nodes => nodes.map(node => ({
    part: node.dataset.character,
    type: node.dataset.componentType,
    inSection: Boolean(node.closest('section.stroke-results')),
  })))
  assert.equal(cells.length, ordinaryCount + strokeCount)
  assert.deepEqual(cells.map(({ inSection }) => inSection), [
    ...Array(ordinaryCount).fill(false), ...Array(strokeCount).fill(true),
  ], 'ordinary results precede the stroke section')
  for (const { part, type, inSection } of cells) {
    assert.equal(unicodeStrokes.includes(part), inSection, 'only Unicode strokes belong in the section')
    assert.equal(type === 'stroke', inSection, 'the type label matches the section')
  }
}
const assertNeutralGlyphColor = async palette => {
  const colors = await palette.locator('.part[data-component-type] .part-text').evaluateAll(nodes => {
    const context = document.createElement('canvas').getContext('2d')
    const rgba = color => {
      context.clearRect(0, 0, 1, 1)
      context.fillStyle = color
      context.fillRect(0, 0, 1, 1)
      return [...context.getImageData(0, 0, 1, 1).data]
    }
    return nodes.map(node => ({
      type: node.closest('.part').dataset.componentType,
      color: getComputedStyle(node).color,
      foreground: rgba(getComputedStyle(node).color),
      background: rgba(getComputedStyle(node.closest('.part')).backgroundColor),
    }))
  })
  const strokes = colors.filter(({ type }) => type === 'stroke')
  const strokeColors = new Set(strokes.map(({ color }) => color))
  const characters = colors.filter(({ type }) => type !== 'stroke')
  assert.equal(strokeColors.size, 1, 'stroke glyphs share a color')
  assert.ok(characters.length > 0, 'the color comparison includes ideographs or radicals')
  for (const { color } of characters) assert.ok(!strokeColors.has(color), 'stroke glyphs have a distinct color')
  const luminance = rgba => rgba.slice(0, 3).map(value => value / 255)
    .map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
    .reduce((sum, value, index) => sum + value * [0.2126, 0.7152, 0.0722][index], 0)
  for (const { foreground, background } of strokes) {
    const rgb = foreground.slice(0, 3)
    assert.ok(Math.max(...rgb) - Math.min(...rgb) <= 20, 'stroke glyphs use neutral gray')
    assert.equal(foreground[3], 255, 'stroke glyphs are opaque')
    assert.equal(background[3], 255, 'the contrast check uses an opaque cell background')
    const ink = luminance(foreground), surface = luminance(background)
    assert.ok((Math.max(ink, surface) + 0.05) / (Math.min(ink, surface) + 0.05) >= 4.5, 'stroke glyph contrast is at least 4.5:1')
  }
}

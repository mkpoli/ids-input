// Run against a preview built with fixtures/parts-groups.html as an entry; IDS_URL and CHROMIUM_PATH optional.
import { chromium } from 'playwright-core'
import { strict as assert } from 'node:assert'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
const url = process.env.IDS_URL ?? 'http://localhost:5264'
const values = locator => locator.evaluateAll(nodes => nodes.map(node => node.dataset.character))
const unicodeStrokes = Array.from({ length: 38 }, (_, index) => String.fromCodePoint(0x31c0 + index))
const assertNoExtraControls = async palette => {
  assert.equal(await palette.locator('.stroke-badge, .stroke-legend, .component-types').count(), 0)
  assert.equal(await palette.getByRole('group', { name: 'Component type', exact: true }).count(), 0)
  assert.equal(await palette.getByRole('button', { name: 'Ideographs & radicals', exact: true }).count(), 0)
  assert.equal(await palette.getByRole('button', { name: 'All', exact: true }).count(), 0)
  assert.equal(await palette.getByRole('button', { name: 'Strokes', exact: true }).count(), 1)
}
const assertDistinctGlyphColor = async palette => {
  const colors = await palette.locator('.part[data-component-type] .part-text').evaluateAll(nodes => nodes.map(node => ({
    type: node.closest('.part').dataset.componentType,
    color: getComputedStyle(node).color,
  })))
  const strokes = new Set(colors.filter(({ type }) => type === 'stroke').map(({ color }) => color))
  const characters = colors.filter(({ type }) => type !== 'stroke')
  assert.equal(strokes.size, 1, 'stroke glyphs share a color')
  assert.ok(characters.length > 0, 'the color comparison includes ideographs or radicals')
  for (const { color } of characters) assert.ok(!strokes.has(color), 'stroke glyphs have a distinct color')
}
try {
  const page = await browser.newPage({ permissions: ['clipboard-read', 'clipboard-write'] })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${url}/fixtures/parts-groups.html`)
  const palette = page.getByRole('group', { name: 'Parts', exact: true })
  const chips = palette.locator('.parts-counts')
  const card = page.getByRole('dialog', { name: 'Character information' })
  const cells = palette.locator('.part')
  const picked = page.locator('#picked')
  await chips.getByRole('button', { name: '1 stroke', exact: true }).waitFor()
  assert.deepEqual(await chips.locator('button').allTextContents(), ['Common', 'Strokes', '1', '4', '?', 'All characters'])
  await chips.getByRole('button', { name: 'Strokes', exact: true }).click()
  assert.deepEqual(await values(cells), ['㇐', '㇣'])
  await assertNoExtraControls(palette)
  await chips.getByRole('button', { name: '1 stroke', exact: true }).click()
  assert.deepEqual(await values(cells), ['一', '㇐', '㇣'])
  await assertNoExtraControls(palette)
  await assertDistinctGlyphColor(palette)
  const stroke = palette.locator('[data-character="㇐"]')
  assert.equal(await stroke.getAttribute('data-component-type'), 'stroke')
  assert.equal(await stroke.getAttribute('data-part-uses'), '0')
  assert.equal(await stroke.locator('.part-text').textContent(), '㇐')
  assert.match(await stroke.getAttribute('aria-label'), /U\+31D0.*Stroke symbol.*CJK STROKE H/)
  assert.equal(await stroke.getAttribute('title'), await stroke.getAttribute('aria-label'))
  // A host without characterInfo still gets identity, exact copying and explicit related-form insertion.
  await stroke.focus()
  await card.getByText('CJK STROKE H', { exact: true }).waitFor()
  await card.getByText('IDS records: 0', { exact: true }).waitFor()
  assert.equal(await picked.textContent(), '')
  await stroke.press('F1')
  assert.equal(await card.locator('.copy').evaluate(node => node === document.activeElement), true)
  await page.keyboard.press('Enter')
  await card.getByText('Copied', { exact: true }).waitFor()
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), '㇐')
  await page.keyboard.press('Escape')
  assert.equal(await stroke.evaluate(node => node === document.activeElement), true)
  await stroke.press('Enter')
  await picked.filter({ hasText: /^㇐$/ }).waitFor()
  await card.getByRole('button', { name: /^Insert 一 · Ideograph · U\+4E00$/ }).click()
  await picked.filter({ hasText: /^一$/ }).waitFor()
  await chips.getByRole('button', { name: '1 stroke', exact: true }).focus()
  await stroke.focus()
  await card.waitFor({ state: 'visible' })
  // Changing the chip removes the anchor and closes its card.
  await chips.getByRole('button', { name: 'Common', exact: true }).click()
  await card.waitFor({ state: 'hidden' })
  assert.deepEqual(await values(cells), ['木'])
  await chips.getByRole('button', { name: '4 strokes', exact: true }).click()
  assert.deepEqual(await values(cells), ['木', '艹'])
  await chips.getByRole('button', { name: 'Strokes', exact: true }).click()
  assert.deepEqual(await values(cells), ['㇐', '㇣'])
  await chips.getByRole('button', { name: '1 stroke', exact: true }).click()
  assert.equal(await chips.getByRole('button', { name: '1 stroke', exact: true }).getAttribute('aria-pressed'), 'true')
  assert.equal(await chips.getByRole('button', { name: 'Strokes', exact: true }).getAttribute('aria-pressed'), 'false')
  assert.deepEqual(await values(cells), ['一', '㇐', '㇣'])
  // Replacing the host adapter aborts its lookup and rejects a late answer without a DOM click.
  await page.evaluate(() => window.identityFixture.delay())
  await palette.locator('[data-character="一"]').focus()
  await page.waitForFunction(() => window.identityFixture.requested)
  await card.waitFor({ state: 'visible' })
  await page.evaluate(() => window.identityFixture.replace())
  await card.waitFor({ state: 'hidden' })
  assert.equal(await page.evaluate(() => window.identityFixture.aborted), true)
  await page.evaluate(() => window.identityFixture.resolve())
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  assert.equal(await card.isVisible(), false)
  assert.equal(await page.getByText('OLD GLOSS', { exact: true }).count(), 0)
  await page.close()

  // Real bundle: no parts disappear, frequent strokes enter Common, and documented pairs are adjacent.
  for (const colorScheme of ['light', 'dark']) {
    const full = await browser.newPage({ viewport: { width: 1440, height: 1400 }, deviceScaleFactor: 2, colorScheme })
    full.on('pageerror', error => errors.push(error.message))
    await full.route('https://glyphatlas.org/**', route => route.abort())
    await full.goto(`${url}/?lang=en`, { waitUntil: 'domcontentloaded' })
    const parts = full.getByRole('group', { name: 'Parts', exact: true })
    await parts.locator('[data-character="㇒"]').waitFor()
    const countChips = parts.locator('.parts-counts')
    const one = countChips.getByRole('button', { name: '1 stroke', exact: true })
    const strokes = countChips.getByRole('button', { name: 'Strokes', exact: true })
    assert.deepEqual((await countChips.locator('button').allTextContents()).slice(0, 3), ['Common', 'Strokes', '1'])
    await assertNoExtraControls(parts)
    await one.click()
    const all = await values(parts.locator('.part'))
    assert.equal(all.length, 61)
    assert.equal(new Set(all).size, 61)
    assert.equal(await parts.locator('.part[data-component-type="stroke"]').count(), 38)
    assert.equal(await parts.locator('.part:not([data-component-type="stroke"])').count(), 23)
    for (const [a, b] of [['一', '㇐'], ['丨', '㇑'], ['丶', '㇔'], ['㇒', '丿'], ['乚', '㇟'], ['亅', '㇚']]) {
      assert.ok(all.includes(a) && all.includes(b), `${a}/${b} are present`)
      assert.equal(all.indexOf(b), all.indexOf(a) + 1, `${a}/${b} adjacent, more-used first`)
    }
    assert.equal(await parts.locator('[data-character="⺄"]').getAttribute('data-component-type'), 'radical')
    assert.equal(await parts.locator('[data-character="乁"]').getAttribute('data-component-type'), 'ideograph')
    await assertNoExtraControls(parts)
    await assertDistinctGlyphColor(parts)
    await strokes.click()
    const onlyStrokes = await values(parts.locator('.part'))
    assert.deepEqual([...onlyStrokes].sort(), unicodeStrokes)
    assert.equal(await parts.locator('.part:not([data-component-type="stroke"])').count(), 0)
    assert.equal(await strokes.getAttribute('aria-pressed'), 'true')
    assert.equal(await one.getAttribute('aria-pressed'), 'false')
    await assertNoExtraControls(parts)
    // Text searches span the palette; clearing one restores the selected chip.
    const search = parts.getByRole('searchbox')
    await search.fill('木')
    await parts.locator('[data-character="木"]').waitFor()
    await search.fill('')
    assert.deepEqual(await values(parts.locator('.part')), onlyStrokes)
    assert.equal(await strokes.getAttribute('aria-pressed'), 'true')
    await search.fill('🦄')
    await parts.getByText('No part matches.', { exact: true }).waitFor()
    assert.equal(await parts.locator('.part').count(), 0)
    await search.fill('')
    assert.deepEqual(await values(parts.locator('.part')), onlyStrokes)
    await one.click()
    assert.deepEqual(await values(parts.locator('.part')), all)
    await countChips.getByRole('button', { name: 'Common', exact: true }).click()
    await parts.locator('[data-character="㇒"]').waitFor()
    await strokes.click()
    assert.deepEqual(await values(parts.locator('.part')), onlyStrokes)
    await full.close()
  }

  const touch = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })
  touch.on('pageerror', error => errors.push(error.message))
  await touch.goto(`${url}/fixtures/parts-groups.html`)
  await touch.locator('.parts-counts').getByRole('button', { name: 'Strokes', exact: true }).tap()
  await touch.locator('[data-character="㇐"]').tap()
  await touch.getByRole('dialog').getByText('CJK STROKE H', { exact: true }).waitFor()
  await touch.locator('#picked').filter({ hasText: /^㇐$/ }).waitFor()
  const bounds = await touch.getByRole('dialog').boundingBox()
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= await touch.evaluate(() => innerWidth))
  await touch.close()
  assert.deepEqual(errors, [])
  console.log('PASS stroke identity: Strokes chip, distinct glyph colors, exact selection/copy, keyboard/touch cards, adapter swaps, source-backed adjacency and all 61 parts')
} finally { await browser.close() }

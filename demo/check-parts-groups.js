// The Components chip row against a small palette: Common, Strokes, stroke counts, and parts whose
// count was never recorded. Run against a devrun server:
//   IDS_URL=http://localhost:5173 bun demo/check-parts-groups.js
import { chromium } from 'playwright-core'
import { strict as assert } from 'node:assert'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
const url = process.env.IDS_URL ?? 'http://localhost:5173'
try {
  const page = await browser.newPage()
  await page.goto(new URL('/fixtures/parts-groups.html', url).href)
  const palette = page.getByRole('group', { name: 'Parts', exact: true })
  const counts = palette.getByRole('group', { name: 'Component groups', exact: true })
  const chips = counts.locator('button')
  const common = counts.getByRole('button', { name: 'Common', exact: true })
  const strokes = counts.getByRole('button', { name: 'Strokes', exact: true })
  const one = counts.getByRole('button', { name: '1 stroke', exact: true })
  const four = counts.getByRole('button', { name: '4 strokes', exact: true })
  const unknown = counts.getByRole('button', { name: 'Stroke count not recorded', exact: true })
  const characters = counts.getByRole('button', { name: 'All characters', exact: true })
  const search = palette.getByRole('searchbox')
  const parts = palette.locator('.parts-grid .part')
  const texts = async () => (await parts.allTextContents()).map(text => text.trim())
  const pressed = async () => (await chips.evaluateAll(els => els.map(el => el.getAttribute('aria-pressed'))))
  const assertChosen = async index => assert.deepEqual(await pressed(), Array.from({ length: 6 }, (_, at) => String(at === index)), 'one chip is chosen at a time')
  const assertNoExtraControls = async () => {
    assert.equal(await palette.locator('.stroke-badge, .stroke-legend, .component-types').count(), 0)
    assert.equal(await palette.getByRole('group', { name: 'Component type', exact: true }).count(), 0)
    assert.equal(await palette.getByRole('button', { name: 'Ideographs & radicals', exact: true }).count(), 0)
    assert.equal(await palette.getByRole('button', { name: 'All', exact: true }).count(), 0)
  }
  const assertNoStrokeSymbols = async () => {
    assert.equal(await palette.locator('.part[data-component-type="stroke"]').count(), 0)
    assert.ok((await texts()).every(part => !/^[\u31c0-\u31e5]$/u.test(part)))
    assert.equal(await palette.locator('section.stroke-results').count(), 0)
  }
  const assertStrokeSection = async (ordinary, symbols) => {
    const section = palette.locator('section.stroke-results')
    assert.equal(await section.count(), 1)
    const region = palette.getByRole('region', { name: 'Stroke symbols', exact: true })
    assert.equal(await region.count(), 1, 'the stroke section has an accessible name')
    assert.equal(await region.evaluate(node => node.matches('section.stroke-results')), true)
    await section.getByRole('heading', { name: 'Stroke symbols', exact: true }).waitFor({ state: 'visible' })
    assert.deepEqual(await texts(), [...ordinary, ...symbols], 'ordinary results precede stroke symbols')
    assert.deepEqual(await section.locator('.part').evaluateAll(nodes => nodes.map(node => node.dataset.character)), symbols)
    assert.equal(await section.locator('.part:not([data-component-type="stroke"])').count(), 0)
    assert.equal(await palette.locator('.part[data-component-type="stroke"]').count(), symbols.length)
  }
  await one.waitFor()
  assert.equal(await page.getByRole('tab', { name: 'Stroke count', exact: true }).count(), 0, 'the stroke counts live in Components')
  assert.equal(await page.getByRole('tab', { name: 'Strokes', exact: true }).count(), 0)
  assert.equal(await page.getByRole('tab', { name: 'Stroke symbols', exact: true }).count(), 0, 'the CJK strokes have a chip in Components')
  assert.equal(await page.getByRole('tab', { name: 'Components', exact: true }).count(), 1, 'the tab names the components')
  assert.deepEqual(await chips.allTextContents(), ['Common', 'Strokes', '1', '4', '?', 'All characters'], 'Strokes sits between Common and 1')
  await assertChosen(0)
  assert.deepEqual(await texts(), ['木'], 'the curated chip shows the curated parts only')
  await assertNoStrokeSymbols()
  await assertNoExtraControls()

  await strokes.click()
  assert.deepEqual(await texts(), ['㇐', '㇣'], 'Strokes shows only Unicode stroke symbols')
  assert.deepEqual(await palette.locator('.parts-class').allTextContents(), ['㇐ Horizontal', 'Other strokes'])
  await assertChosen(1)
  await assertNoExtraControls()
  await one.click()
  assert.deepEqual(await texts(), ['一'], 'one stroke shows the real CJK/radical parts')
  assert.deepEqual(await palette.locator('.parts-class').allTextContents(), ['㇐ Horizontal'], 'one stroke keeps its first-stroke heading')
  await assertNoStrokeSymbols()
  assert.equal(await one.getAttribute('title'), '1 stroke', 'the count keeps its name for hover and screen readers')
  await assertChosen(2)
  await assertNoExtraControls()
  await four.click()
  assert.deepEqual(await texts(), ['木', '艹'], 'a count shows every ordinary part of it')
  await assertNoStrokeSymbols()
  assert.equal(await four.getAttribute('title'), '4 strokes', 'the count keeps its name for hover and screen readers')
  await assertChosen(3)
  await unknown.click()
  assert.deepEqual(await texts(), ['𒖨'], 'the unknown chip shows the ordinary parts without a stroke count')
  await assertNoStrokeSymbols()
  assert.deepEqual(await palette.locator('.parts-class').allTextContents(), ['First stroke not recorded'])
  await assertChosen(4)

  await strokes.click()
  await search.fill('1')
  await assertStrokeSection(['一'], ['㇐', '㇣'])
  await assertChosen(1)
  await search.fill('㇣一㇐')
  await assertStrokeSection(['一'], ['㇐', '㇣'])
  await search.fill('㇣')
  await assertStrokeSection([], ['㇣'])
  await search.fill('木')
  assert.deepEqual(await texts(), ['木'], 'a text search reaches parts outside the selected chip')
  await assertNoStrokeSymbols()
  await search.fill('')
  assert.deepEqual(await texts(), ['㇐', '㇣'], 'an empty search restores Strokes')
  await assertChosen(1)
  await search.fill('   ')
  assert.deepEqual(await texts(), ['㇐', '㇣'], 'whitespace is an empty search')
  await search.fill('🦄')
  await palette.getByText('No part matches.', { exact: true }).waitFor()
  assert.deepEqual(await texts(), [], 'a zero-result search does not fall back to Strokes')
  assert.equal(await palette.locator('.parts-class').count(), 0)
  assert.equal(await palette.locator('section.stroke-results').count(), 0)
  await search.fill('')
  assert.deepEqual(await texts(), ['㇐', '㇣'])
  assert.equal(await palette.getByText('No part matches.', { exact: true }).count(), 0)
  await assertChosen(1)

  await characters.click()
  assert.equal(await characters.getAttribute('aria-pressed'), 'true')
  assert.equal(await strokes.getAttribute('aria-pressed'), 'false')
  assert.equal(await common.getAttribute('aria-pressed'), 'false')
  await strokes.click()
  assert.deepEqual(await texts(), ['㇐', '㇣'], 'Strokes returns from All characters')
  await assertChosen(1)
  await common.click()
  assert.deepEqual(await texts(), ['木'], 'the curated chip comes back')
  await assertChosen(0)
  await assertNoStrokeSymbols()
  await assertNoExtraControls()

  // Recent keeps each kind's recency order while ordinary parts come first.
  await palette.locator('[data-character="木"]').press('Enter')
  await page.locator('#picked').filter({ hasText: /^木$/ }).waitFor()
  await one.click()
  await palette.locator('[data-character="一"]').press('Enter')
  await page.locator('#picked').filter({ hasText: /^一$/ }).waitFor()
  await strokes.click()
  await palette.locator('[data-character="㇐"]').press('Enter')
  await page.locator('#picked').filter({ hasText: /^㇐$/ }).waitFor()
  await palette.locator('[data-character="㇣"]').press('Enter')
  await page.locator('#picked').filter({ hasText: /^㇣$/ }).waitFor()
  await palette.getByRole('tab', { name: 'Recent', exact: true }).click()
  await assertStrokeSection(['一', '木'], ['㇣', '㇐'])
  await search.fill('1')
  await assertStrokeSection(['一'], ['㇐', '㇣'])
  await search.fill('')
  await assertStrokeSection(['一', '木'], ['㇣', '㇐'])
  await palette.getByRole('tab', { name: 'Components', exact: true }).click()
  assert.deepEqual(await texts(), ['㇐', '㇣'])
  await assertChosen(1)
  console.log('PASS Components chips: Common, Strokes, ordinary counts, unknown heading, All characters and split global searches/Recent')
} finally { await browser.close() }

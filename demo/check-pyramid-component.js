// Run with IDS_URL and CHROMIUM_PATH; optionally set IDS_PYRAMID_SHOTS.
import { chromium } from 'playwright-core'
import { strict as assert } from 'node:assert'
import { mkdirSync } from 'node:fs'
import { pyramidRows, parse } from '../src/core/index.js'

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
try {
  for (const colorScheme of ['light', 'dark']) {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 2, colorScheme })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(process.env.IDS_URL ?? 'http://127.0.0.1:5197/?lang=en')
    const field = page.locator('.ids-field input')
    await field.fill('')
    await field.press('Tab')
    await page.getByRole('tab', { name: 'Templates', exact: true }).click()
    const group = page.locator('.ids-pyramid').first()
    const part = page.locator('input[id$="-generator-part"]')
    const capture = async prefix => {
      if (!process.env.IDS_PYRAMID_SHOTS) return
      mkdirSync(process.env.IDS_PYRAMID_SHOTS, { recursive: true })
      await group.scrollIntoViewIfNeeded()
      await page.screenshot({ path: `${process.env.IDS_PYRAMID_SHOTS}/${prefix}-${colorScheme}.png` })
    }
    if (process.env.IDS_PYRAMID_BASELINE) {
      await capture('before')
      await page.close()
      continue
    }
    const rows = group.locator('input[type=number]')
    const insert = group.getByRole('button', { name: 'Insert', exact: true })
    const preset = group.locator('[data-pyramid="3"]')
    assert.equal(await part.inputValue(), '口')
    for (const invalid of ['木口', '木ˊ']) {
      await part.fill(invalid)
      assert.equal(await part.getAttribute('aria-invalid'), 'true')
      assert.equal(await insert.isDisabled(), true)
      for (const button of await group.locator('[data-pyramid]').all()) assert.equal(await button.isDisabled(), true)
    }
    await part.fill('木')
    assert.equal(await part.getAttribute('aria-invalid'), 'false')
    assert.match(await preset.getAttribute('aria-label'), /木/)
    await rows.fill('1')
    await part.press('Enter')
    assert.equal(await field.inputValue(), '', 'invalid row count cannot submit')
    await rows.fill('5')
    await page.getByRole('tab', { name: 'Parts', exact: true }).click()
    await page.getByRole('tab', { name: 'Templates', exact: true }).click()
    assert.equal(await part.inputValue(), '木')
    await preset.click()
    assert.deepEqual(pyramidRows(parse(await field.inputValue()).tree), { cell: '木', layers: 3, count: 6, reverse: false })
    assert.equal(await part.inputValue(), '木', 'insertion keeps the typed component')
    await field.fill('')
    await field.press('Tab')
    await group.getByRole('checkbox', { name: 'Reverse', exact: true }).check()
    await rows.fill('5')
    await part.press('Enter')
    assert.deepEqual(pyramidRows(parse(await field.inputValue()).tree), { cell: '木', layers: 5, count: 15, reverse: true })
    await page.locator('.ids-preview[data-step="composed"]').waitFor()
    await capture('after')
    await field.fill('')
    await field.press('Tab')
    await part.fill('木')
    await page.locator('[data-repeat="2+3"]').click()
    assert.equal(await field.inputValue(), '⿱⿰木木⿲木木木')
    await field.fill('')
    await field.press('Tab')
    const customRows = page.locator('.ids-repeat-custom input')
    const customInsert = page.locator('[data-repeat-custom]')
    await customRows.fill('3 4')
    await customInsert.click()
    assert.equal(await field.inputValue(), '⿱⿲木木木⿰⿰木木⿰木木')
    await field.fill('')
    await customRows.fill('2 5')
    assert.equal(await customRows.getAttribute('aria-invalid'), 'true')
    assert.equal(await customInsert.isDisabled(), true)
    await customRows.fill('２＋３')
    await customInsert.click()
    assert.equal(await field.inputValue(), '⿱⿰木木⿲木木木')
    await field.fill('')
    await page.locator('.ids-repeat input').first().fill('口')
    await customRows.fill('2 1 2')
    await customInsert.click()
    assert.equal(await field.inputValue(), '⿳⿰木木木⿰口口')
    await field.press('Tab')
    await page.locator('[data-five="212"]').click()
    assert.equal(await field.inputValue(), '⿳⿰木木木⿰木木')
    // A part may be a whole description, or nothing for a pyramid of empty slots.
    await group.getByRole('checkbox', { name: 'Reverse', exact: true }).uncheck()
    await field.fill('')
    await field.press('Tab')
    await part.fill('⿱众⿰众众')
    assert.equal(await part.getAttribute('aria-invalid'), 'false', 'a description is a part')
    await group.locator('[data-pyramid="2"]').click()
    assert.equal(await field.inputValue(), '⿱⿱众⿰众众⿰⿱众⿰众众⿱众⿰众众', 'a 2-row pyramid of a description')
    await field.fill('')
    await field.press('Tab')
    await part.fill('')
    await group.locator('[data-pyramid="2"]').click()
    assert.equal(await field.inputValue(), '⿱⬚⿰⬚⬚', 'an empty part lays out empty slots')
    assert.equal(await part.getAttribute('aria-invalid'), 'false')
    await field.fill('')
    await field.press('Tab')
    for (const component of ['𠮷', '木\uFE00', '가']) {
      await field.fill('')
      await field.press('Tab')
      await part.fill(component)
      assert.equal(await part.getAttribute('aria-invalid'), 'false', component)
      await preset.click()
      assert.equal(pyramidRows(parse(await field.inputValue()).tree)?.cell, component)
    }
    assert.deepEqual(errors, [])
    console.log(`PASS ${colorScheme}: typed parts and descriptions, slots, validation, presets, 2-row pyramids, custom rows, reverse, Enter, tab persistence, Unicode components`)
    await page.close()
  }
} finally { await browser.close() }

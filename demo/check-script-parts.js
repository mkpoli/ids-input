// Run against a devrun server: IDS_URL=http://localhost:5173 bun demo/check-script-parts.js
import { chromium } from 'playwright-core'
import { strict as assert } from 'node:assert'

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
const url = process.env.IDS_URL ?? 'http://localhost:5173'
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  const page = await context.newPage()
  await page.goto(url)
  await page.getByRole('tab', { name: 'Parts', exact: true }).click()
  assert.equal(await page.getByRole('combobox', { name: 'Script' }).count(), 0)
  await page.getByRole('tab', { name: 'Gongche', exact: true }).click()
  await page.locator('.gongche-guide').waitFor()
  assert.ok(await page.locator('.parts-grid .part').count() > 0, 'Gongche remains available')
  for (const [name, count] of [['Bopomofo', 82], ['Letters & numbers', 310], ['Tangut', 768]]) {
    await page.getByRole('tab', { name, exact: true }).click()
    await page.locator('.parts-grid .part').first().waitFor()
    assert.equal(await page.locator('.parts-grid .part').count(), name === 'Tangut' ? 120 : count, `${name} remains available`)
    if (name === 'Bopomofo') assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), 'ㄅ')
  }
  assert.equal(await page.getByRole('tab', { name: 'Han', exact: true }).count(), 0)
  assert.equal(await page.getByRole('tab', { name: 'Cyrillic', exact: true }).count(), 0)
  await page.getByRole('tab', { name: 'Other scripts', exact: true }).click()
  const selector = page.getByRole('combobox', { name: 'Script' })
  assert.equal(await selector.inputValue(), 'Grek')
  await page.locator('.script-pages').waitFor()
  await selector.selectOption('Hebr')
  await page.locator('.parts-filter').fill('U+05D0')
  assert.equal(await page.locator('.parts-grid .part').count(), 1)
  assert.equal((await page.locator('.parts-grid .part').first().innerText()).trim(), 'א')
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), 'א')
  await selector.selectOption('Arab')
  await page.locator('.parts-filter').fill('ش')
  assert.ok(await page.locator('.parts-grid .part').count() > 0, 'Arabic part is searchable')
  await selector.selectOption('Grek')
  await page.locator('.parts-filter').fill('木')
  assert.equal(await page.locator('.parts-grid .part').count(), 0, 'search stays within the selected script')
  await page.getByRole('tab', { name: 'Bopomofo', exact: true }).click()
  assert.equal(await page.getByRole('combobox', { name: 'Script' }).count(), 0)
  await page.getByRole('tab', { name: 'Other scripts', exact: true }).click()
  assert.equal(await selector.inputValue(), 'Grek')
  await context.close()

  const offline = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  await offline.route('**/script-parts.json.gz*', route => route.abort())
  const disconnected = await offline.newPage()
  await disconnected.goto(url)
  await disconnected.getByRole('tab', { name: 'Parts', exact: true }).click()
  await disconnected.getByRole('tab', { name: 'Other scripts', exact: true }).click()
  await disconnected.getByText('Additional script parts could not be loaded.').waitFor()
  await disconnected.getByRole('tab', { name: 'Bopomofo', exact: true }).click()
  assert.equal(await disconnected.locator('.parts-grid .part').count(), 82, 'existing tabs work if the catalog fails')
  await disconnected.getByRole('tab', { name: 'Other scripts', exact: true }).click()
  await offline.unroute('**/script-parts.json.gz*')
  await disconnected.getByRole('button', { name: 'Retry', exact: true }).click()
  await disconnected.locator('.script-pages').waitFor()
  assert.equal(await disconnected.locator('.parts-grid .part').count(), 120)
  await offline.close()

  const custom = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  await custom.route('**/script-parts.json.gz*', route => route.abort())
  const fixture = await custom.newPage()
  await fixture.goto(new URL('/fixtures/script-parts.html', url).href)
  await fixture.getByRole('tab', { name: 'Other scripts', exact: true }).click()
  const scripts = fixture.getByRole('combobox', { name: 'Script' })
  await scripts.selectOption('Pcun')
  await fixture.getByText('Additional script parts could not be loaded.').waitFor()
  const customPart = fixture.locator('.parts-grid button[title^="𒖨 ·"]')
  await customPart.waitFor()
  await fixture.locator('.parts-filter').fill('𒖨')
  assert.equal(await customPart.count(), 1)
  await customPart.focus()
  await customPart.press('Enter')
  assert.equal((await fixture.locator('#picked').innerText()).trim(), '𒖨')
  await custom.close()
  console.log('PASS additional scripts, existing tabs, catalog retry and custom adapter')
} finally { await browser.close() }

// Run against a local devrun server with IDS_URL and optional IDS_TINT_SHOTS.
import { chromium } from 'playwright-core'
import { strict as assert } from 'node:assert'
import { mkdirSync } from 'node:fs'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
try {
  for (const scheme of ['light', 'dark']) {
    const page = await browser.newPage({viewport: {width:1440, height:900}, deviceScaleFactor:2, colorScheme:scheme})
    await page.route('https://glyphatlas.org/**', route => route.abort())
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(process.env.IDS_URL ?? 'http://localhost:5186', {waitUntil:'domcontentloaded'})
    const field = page.locator('.ids-field input')
    await field.fill('⿰⿱木火⿱日月')
    await field.press('Tab')
    await page.mouse.move(0,0)
    assert.equal(await page.locator('.sequence-paint .tinted').count(), 0)
    await page.locator('.ids-op[data-path="0"]').hover()
    assert.equal(await page.locator('.sequence-paint .tinted').count(), 3)
    assert.equal(await page.locator('.ids-tree .tinted').count(), 3)
    assert.equal(await page.locator('.sequence-paint .hovered').nth(1).evaluate(el=>getComputedStyle(el).borderRadius), '0px')
    await page.mouse.move(0,0)
    assert.equal(await page.locator('.sequence-paint .tinted').count(), 0)
    await page.getByRole('button', {name:'Settings', exact:true}).click()
    const mode = page.getByRole('combobox', {name:'Part tint', exact:true})
    assert.equal(await mode.inputValue(), 'hover')
    await mode.selectOption('on')
    await page.keyboard.press('Escape')
    assert.equal(await page.locator('.sequence-paint .tinted').count(), 7)
    assert.equal(await page.locator('.ids-tree .tinted').count(), 7)
    assert.equal(await page.locator('.sequence-paint span').nth(1).evaluate(el=>getComputedStyle(el).borderRadius), '0px')
    const edges = await page.locator('.sequence-paint span').evaluateAll(els=>els.map(el=>({left:el.getBoundingClientRect().left,right:el.getBoundingClientRect().right})))
    for(let i=1;i<edges.length;i++) assert.ok(Math.abs(edges[i].left-edges[i-1].right)<.1)
    if(process.env.IDS_TINT_SHOTS) {
      mkdirSync(process.env.IDS_TINT_SHOTS,{recursive:true})
      await page.evaluate(()=>document.fonts.ready)
      await page.screenshot({path:`${process.env.IDS_TINT_SHOTS}/after-shape-${scheme}.png`,clip:{x:0,y:60,width:990,height:520}})
    }
    await page.reload({waitUntil:'domcontentloaded'})
    await field.waitFor()
    assert.equal(await page.locator('.sequence-paint .tinted').count(),7)
    await page.locator('#tree-tab').click()
    assert.equal(await page.locator('[role=treeitem].tinted').count(),7)
    if(process.env.IDS_TINT_SHOTS) await page.screenshot({path:`${process.env.IDS_TINT_SHOTS}/after-tree-${scheme}.png`,clip:{x:0,y:60,width:990,height:520}})
    await page.getByRole('button',{name:'Settings',exact:true}).click()
    await mode.selectOption('off')
    await page.keyboard.press('Escape')
    await page.locator('[role=treeitem][data-path="0"]').hover()
    assert.equal(await page.locator('.sequence-paint .tinted').count(),0)
    assert.equal(await page.locator('[role=treeitem].tinted').count(),0)
    assert.equal(await page.locator('.sequence-paint .hovered').count(),3)
    await page.locator('[role=treeitem][data-path="0"]').click()
    assert.equal(await page.locator('.sequence-paint .selected').count(),3)
    await page.locator('[role=treeitem][data-path="0.0"]').hover()
    assert.equal(await page.locator('.sequence-paint .selected').nth(1).evaluate(el=>getComputedStyle(el).borderRadius),'0px')
    await page.reload({waitUntil:'domcontentloaded'})
    await field.waitFor()
    await page.getByRole('button',{name:'Settings',exact:true}).click()
    assert.equal(await mode.inputValue(),'off')
    await mode.selectOption('hover')
    assert.equal(await page.evaluate(()=>localStorage.getItem('ids-input:tintMode')),null)
    if(process.env.IDS_TINT_SHOTS) await page.getByRole('dialog').screenshot({path:`${process.env.IDS_TINT_SHOTS}/settings-${scheme}.png`})
    await page.keyboard.press('Escape')
    await page.locator('#tree-tab').click()
    await page.locator('[role=treeitem][data-path="1"]').hover()
    assert.equal(await page.locator('[role=treeitem].tinted').count(),3)
    assert.deepEqual(errors,[])
    await page.close()
    console.log(`PASS ${scheme}: default hover, on/off, persistence, continuous tint, linked selection`)
  }
} finally { await browser.close() }

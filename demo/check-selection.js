// Run against a local devrun server: IDS_URL=http://localhost:5186 bun demo/check-selection.js
import { chromium } from 'playwright-core'
import { strict as assert } from 'node:assert'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
try {
  const page = await browser.newPage({ viewport: {width: 1440, height: 900}, deviceScaleFactor: 2 })
  await page.route('https://glyphatlas.org/**', route => route.abort())
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.IDS_URL ?? 'http://localhost:5186', { waitUntil: 'domcontentloaded' })
  const field = page.locator('.ids-field input')
  const select = async (start, end) => {
    await field.focus()
    await field.evaluate((field, [start, end]) => {field.setSelectionRange(start, end); field.dispatchEvent(new Event('select'))}, [start, end])
  }
  await field.fill('⿰⿱木火⿱日月')
  await select(1, 4)
  assert.equal(await page.locator('.ids-op[data-path="0"]').getAttribute('aria-pressed'), 'true')
  await page.locator('.ids-slot').fill('水')
  await page.locator('.ids-slot').press('Enter')
  assert.equal(await field.inputValue(), '⿰水⿱日月')
  await field.fill('⿰⿱木火⿱日月')
  await page.locator('.ids-op[data-path="1"]').click()
  assert.deepEqual(await field.evaluate(f => [f.selectionStart, f.selectionEnd]), [4, 7])
  await field.focus()
  await page.keyboard.insertText('水')
  assert.equal(await field.inputValue(), '⿰⿱木火水')
  await field.fill('⿰⿱木火水')
  await select(1, 2)
  await page.keyboard.insertText('日')
  assert.equal(await field.inputValue(), '⿰日水')
  assert.deepEqual(await field.evaluate(f => [f.selectionStart, f.selectionEnd]), [2, 2])
  await select(1, 2)
  await page.keyboard.press('Backspace')
  assert.equal(await field.inputValue(), '⿰⬚水')
  await page.keyboard.press('Control+z')
  assert.equal(await field.inputValue(), '⿰日水')
  await page.keyboard.press('Control+Shift+z')
  assert.equal(await field.inputValue(), '⿰⬚水')
  await field.fill('⿰𠀀\u{E0100}水')
  await select(2, 3)
  await page.keyboard.insertText('木')
  assert.equal(await field.inputValue(), '⿰木水')
  await page.locator('#tree-tab').click()
  await page.locator('[role=treeitem][data-path="1"]').click()
  assert.deepEqual(await field.evaluate(f => [f.selectionStart, f.selectionEnd]), [2, 3])
  await page.locator('[role=treeitem][data-path="0"]').hover()
  assert.equal(await page.locator('.sequence-paint .hovered').count(), 1)
  assert.deepEqual(errors, [])
  console.log('PASS text/graph/list selection, subtree replacement, deletion, Unicode, hover')
} finally { await browser.close() }

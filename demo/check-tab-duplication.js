// Both entry points copy the intended document without linking its later edits to the source.
export async function checkTabDuplication(open, assert) {
  const page = await open('#' + encodeURIComponent('⿰木口'))
  const tabs = page.locator('.tabbar [role="tab"]')
  const active = () => page.locator('.tabbar .tab.on').getAttribute('data-tab-id')
  const value = () => page.locator('.ids-field input').inputValue()
  const tab = id => page.locator(`.tab[data-tab-id="${id}"] [role="tab"]`)
  const fileDuplicate = async () => {
    await page.getByRole('menuitem', { name: 'File', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Duplicate tab', exact: true }).click()
  }
  try {
    const source = await active()
    await page.locator('.ids-field input').fill('⿱木口')
    await fileDuplicate()
    const copy = await active()
    assert(copy !== source && await tabs.count() === 2, 'File creates a separate tab')
    assert(await value() === '⿱木口', 'File duplicates the active text')
    assert(await page.locator('.tabbar .tab-dot').count() === 2, 'the edited marker is copied')
    await page.keyboard.press('Control+z')
    assert(await value() === '⿰木口', 'the duplicate has its own undo history')
    await tab(source).click()
    assert(await value() === '⿱木口', 'undo in the duplicate leaves the source intact')
    await tab(copy).click()
    await tab(source).click({ button: 'right' })
    assert(await active() === copy, 'right-click does not change the active document')
    await page.getByRole('menuitem', { name: 'Duplicate tab', exact: true }).click()
    const contextCopy = await active()
    assert(await tabs.count() === 3 && await value() === '⿱木口', 'context menu duplicates its inactive source')
    const order = await page.locator('.tabbar .tab').evaluateAll(els => els.map(el => el.dataset.tabId))
    assert(order[0] === source && order[1] === contextCopy && order[2] === copy, 'the duplicate is inserted beside its source')
    assert(await tab(contextCopy).evaluate(el => el === document.activeElement), 'context duplication focuses the new tab')
    await page.keyboard.press('Shift+F10')
    assert(await page.getByRole('menuitem', { name: 'Duplicate tab', exact: true }).evaluate(el => el === document.activeElement), 'Shift+F10 focuses the tab action')
    await page.keyboard.press('Escape')
    assert(await page.locator('.tab-menu').count() === 0 && await tab(contextCopy).evaluate(el => el === document.activeElement), 'Escape dismisses and restores tab focus')
    await tab(contextCopy).click({ button: 'right' })
    await page.locator('.ids-field input').click()
    assert(await page.locator('.tab-menu').count() === 0, 'outside click dismisses the menu')
    await page.locator('.ids-field input').fill('木木')
    await fileDuplicate()
    assert(await value() === '木木', 'an incomplete draft duplicates without normalization loss')
    await page.setViewportSize({ width: 375, height: 812 })
    await page.getByRole('button', { name: 'Menu', exact: true }).click()
    await page.locator('dialog[open]').getByRole('button', { name: 'Duplicate tab', exact: true }).click()
    assert(await tabs.count() === 5 && await value() === '木木', 'the phone File menu duplicates a tab')
    await page.locator('.tab.on [role="tab"]').click({ button: 'right' })
    const box = await page.locator('.tab-menu').boundingBox()
    assert(box.x >= 8 && box.x + box.width <= 367, 'the context menu fits the phone viewport')
    await page.keyboard.press('Escape')
    assert(!page.errors.length, `duplicate tab page errors: ${page.errors.join('; ')}`)
  } finally { await page.context().close() }
}

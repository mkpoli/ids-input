// Run against a local devrun server: IDS_URL=http://localhost:5186 bun demo/check-selection.js
import { chromium } from 'playwright-core'
import { strict as assert } from 'node:assert'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
try {
  const page = await browser.newPage({ viewport: {width: 1440, height: 900}, deviceScaleFactor: 2 })
  await page.route('https://glyphatlas.org/**', route => route.abort())
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.IDS_URL ?? 'http://localhost:5186', { waitUntil: 'domcontentloaded' })
  const field = page.locator('.ids-field input')
  const select = async (start, end) => {
    await field.focus()
    await field.evaluate((field, [start, end]) => {field.setSelectionRange(start, end); field.dispatchEvent(new Event('select'))}, [start, end])
  }
  await field.fill('⿰木日')
  await select(2, 2)
  await page.keyboard.insertText('水')
  assert.equal(await field.inputValue(), '⿲木水日')
  await page.keyboard.press('Control+z')
  assert.equal(await field.inputValue(), '⿰木日')
  await page.keyboard.press('Control+Shift+z')
  assert.equal(await field.inputValue(), '⿲木水日')
  await field.fill('⿰木日')
  await select(1, 1)
  await page.keyboard.insertText('⿱')
  assert.equal(await field.inputValue(), '⿰⿱木⬚日')
  await field.fill('⿰木日')
  await select(1, 2)
  await page.keyboard.insertText('⿱')
  assert.equal(await field.inputValue(), '⿰⿱⬚⬚日')
  await field.fill('⿰木日')
  await select(2, 2)
  await field.evaluate(f => {
    const clipboardData = new DataTransfer(); clipboardData.setData('text/plain', '水')
    f.dispatchEvent(new ClipboardEvent('paste', {clipboardData, bubbles:true, cancelable:true}))
  })
  assert.equal(await field.inputValue(), '⿲木水日')
  // A zi.tools entry reads as its description: the notes around it are left out, and a caret
  // beside a part still names that part.
  const settled = (text) => page.waitForFunction(want => document.querySelector('.ids-field input')?.value === want, text)
  await field.fill('{士}⿱十一')
  await settled('⿱十一')
  await select(2, 2)
  await page.keyboard.insertText('水')
  assert.equal(await field.inputValue(), '⿳十水一')
  await field.fill('⿻乚一(.,T)')
  await settled('⿻乚一')
  // A zi.tools modifier stays with its operator, and a part typed after it keeps its place.
  await field.fill('⿴[1]囗水')
  await page.waitForFunction(() => document.querySelector('.ids-field input')?.value === '⿴[1]囗水')
  await page.waitForFunction(() => !/Composing/.test(document.querySelector('.ids-preview-meta')?.textContent ?? 'Composing'))
  assert.equal(await field.inputValue(), '⿴[1]囗水')
  await field.press('End')
  await page.keyboard.insertText('一')
  assert.equal((await field.inputValue()).startsWith('⿴[1]'), true)
  // A stroke chain that names a character reads as that character.
  await field.fill('⿰#(H)木')
  await page.waitForFunction(() => document.querySelector('.ids-field input')?.value === '⿰一木')
  assert.equal(await field.getAttribute('aria-invalid'), 'false')
  // The bundled table names 甲 by its modified description, ahead of 申 by the plain one.
  await field.fill('⿻[1:]丨日')
  await page.waitForFunction(() => /U\+7532/.test(document.querySelector('.ids-preview-meta')?.textContent ?? ''))


  await field.fill('⿰木日')
  await select(2, 2)
  const cdp = await page.context().newCDPSession(page)
  await cdp.send('Input.imeSetComposition', {text:'みず', selectionStart:2, selectionEnd:2})
  assert.notEqual(await field.evaluate(f=>getComputedStyle(f).webkitTextFillColor), 'rgba(0, 0, 0, 0)')
  await cdp.send('Input.insertText', {text:'水'})
  assert.equal(await field.inputValue(), '⿲木水日')
  await field.fill('⿰木日')
  await select(2, 2)
  await page.locator('.ids-slot').fill('水')
  await page.locator('.ids-slot').press('Enter')
  assert.equal(await field.inputValue(), '⿲木水日')
  await field.fill('⿾'.repeat(63)+'木')
  await select(64,64)
  await page.keyboard.insertText('水')
  assert.equal(await field.inputValue(), '⿾'.repeat(63)+'木')
  await select(63,64)
  await page.keyboard.insertText('⿰木水')
  assert.equal(await field.inputValue(), '⿾'.repeat(63)+'木')
  await field.fill('⿰木日')
  await select(1,2)
  await page.keyboard.insertText('水')
  await page.keyboard.insertText('火')
  assert.equal(await field.inputValue(), '⿲水火日')
  await field.fill('⿰木日')
  await select(3,3)
  await page.keyboard.insertText('⿱')
  assert.equal(await field.inputValue(), '⿲木日⿱⬚⬚')
  assert.deepEqual(errors, [])
  console.log('PASS caret typing, operator insertion/replacement, paste, IME, palette, undo, length limit')
} finally { await browser.close() }

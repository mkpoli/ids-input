// Run against a devrun server: IDS_URL=http://localhost:5173 bun demo/check-han-parts.js
import { chromium } from 'playwright-core'
import { strict as assert } from 'node:assert'

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH })
const url = process.env.IDS_URL ?? 'http://localhost:5173'
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  const page = await context.newPage()
  await page.goto(url)
  await page.getByRole('tab', { name: 'Parts', exact: true }).click()
  await page.getByRole('tab', { name: 'Components', exact: true }).click()
  await page.getByRole('button', { name: 'All characters', exact: true }).click()
  await page.locator('.script-pages').waitFor()
  assert.equal(await page.locator('.parts-grid .part').count(), 120, 'characters are paged')
  assert.match(await page.locator('.script-pages').innerText(), /103,352/)
  await page.locator('.parts-filter').fill('U+20001')
  assert.equal(await page.locator('.parts-grid .part').count(), 1, 'a code point finds one character')
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '𠀁')
  await page.locator('.parts-filter').fill('鬱')
  assert.equal(await page.locator('.parts-grid .part').first().getAttribute('data-character'), '鬱')
  await page.locator('.parts-filter').fill('')
  await page.getByRole('button', { name: '23 strokes and up', exact: true }).click()
  assert.match(await page.locator('.script-pages').innerText(), /5,045/)
  await page.locator('.parts-filter').fill('U+9B31')
  assert.equal(await page.locator('.parts-grid button[data-character="鬱"]').count(), 1, '23 and up holds 鬱')
  await page.locator('.parts-filter').fill('U+9EA4')
  assert.equal(await page.locator('.parts-grid button[data-character="麤"]').count(), 1, '23 and up holds 麤')
  await page.locator('.parts-filter').fill('')
  assert.equal(await page.getByRole('button', { name: 'Stroke count not recorded', exact: true }).count(), 0, 'every character has a count')
  await page.getByRole('button', { name: 'All characters', exact: true }).click()
  assert.match(await page.locator('.script-pages').innerText(), /103,352/)
  await page.getByRole('button', { name: 'Common', exact: true }).click()
  assert.ok(await page.locator('.parts-grid .part').count() > 0, 'the curated parts remain available')
  await context.close()

  const offline = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  await offline.route('**/han-parts.json.gz*', route => route.abort())
  const disconnected = await offline.newPage()
  await disconnected.goto(url)
  await disconnected.getByRole('tab', { name: 'Parts', exact: true }).click()
  await disconnected.getByRole('button', { name: 'All characters', exact: true }).click()
  await disconnected.getByText("The composer's Han characters could not be loaded.").waitFor()
  await offline.unroute('**/han-parts.json.gz*')
  await disconnected.getByRole('button', { name: 'Retry', exact: true }).click()
  await disconnected.locator('.script-pages').waitFor()
  assert.equal(await disconnected.locator('.parts-grid .part').count(), 120)
  await offline.close()

  const custom = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  const fixture = await custom.newPage()
  await fixture.goto(new URL('/fixtures/script-parts.html', url).href)
  await fixture.getByRole('button', { name: 'All characters', exact: true }).click()
  await fixture.locator('.parts-filter').fill('U+20001')
  const part = fixture.locator('.parts-grid button[data-character="𠀁"]')
  await part.waitFor()
  await part.focus()
  await part.press('Enter')
  assert.equal((await fixture.locator('#picked').innerText()).trim(), '𠀁')
  await custom.close()
  console.log('PASS Han characters, paging, search, curated parts, retry and picking')
} finally { await browser.close() }
